#!/usr/bin/env python3
"""Measure every co-driver clip (peak and mean level, dBFS) and write scripts/race/co_driver_levels.gd.

CoDriverVoice uses the table to level-match calls and to keep each clip below clipping, whatever the
voice-volume slider is set to. Re-run after adding or replacing clips:
    python3 tools/measure_codriver.py
"""
import glob, os, re, subprocess, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
CLIPS = os.path.join(ROOT, "audio", "codriver")
OUT = os.path.join(ROOT, "scripts", "race", "co_driver_levels.gd")


def measure(path):
    r = subprocess.run(["ffmpeg", "-hide_banner", "-nostats", "-i", path, "-af", "volumedetect", "-f", "null", "-"],
                       capture_output=True, text=True)
    peak = re.search(r"max_volume: (-?[\d.]+) dB", r.stderr)
    mean = re.search(r"mean_volume: (-?[\d.]+) dB", r.stderr)
    if not peak or not mean:
        sys.exit("could not measure " + path)
    return float(peak.group(1)), float(mean.group(1))


voices = {"george": CLIPS}
for d in sorted(glob.glob(os.path.join(CLIPS, "*", ""))):
    voices[os.path.basename(os.path.dirname(d))] = d
lines = ["class_name CoDriverLevels", "## GENERATED by tools/measure_codriver.py - do not edit.",
         "## voice -> call -> [peak dBFS, mean dBFS]", "const LEVELS := {"]
for voice, folder in voices.items():
    rows = []
    for f in sorted(glob.glob(os.path.join(folder, "*.ogg"))):
        peak, mean = measure(f)
        rows.append('\t\t"%s": [%.1f, %.1f]' % (os.path.splitext(os.path.basename(f))[0], peak, mean))
    lines.append('\t"%s": {\n%s\n\t},' % (voice, ",\n".join(rows)))
lines.append("}")
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote", OUT, sum(len(glob.glob(os.path.join(f, "*.ogg"))) for f in voices.values()), "clips")
